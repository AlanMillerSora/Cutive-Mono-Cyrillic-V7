#!/usr/bin/env python3
"""Export an editable UFO + Glyphs source from the finished font.

The shipped build is generated by source/build.py from the drawing code;
this export gives designers a standard UFO/Glyphs file of the exact
outlines that ship, so the project stays editable in the usual tools.
"""
from __future__ import annotations

import sys
from pathlib import Path

import glyphsLib
import ufoLib2
from fontTools.pens.qu2cuPen import Qu2CuPen
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.pointPen import SegmentToPointPen
from fontTools.ttLib import TTFont
from fontTools.ufoLib.glifLib import GlyphSet

ROOT = Path(__file__).resolve().parents[2]
TTF = ROOT / "fonts" / "CutiveMono-Cyrillic-Regular.ttf"
UFO = ROOT / "source" / "CutiveMonoCyrillic.ufo"
GLYPHS = ROOT / "source" / "CutiveMonoCyrillic.glyphs"


def main() -> None:
    font = TTFont(TTF)
    glyphset = font.getGlyphSet()
    upm = font["head"].unitsPerEm

    ufo = ufoLib2.Font()
    ufo.info.familyName = "Cutive Mono Cyrillic"
    ufo.info.styleName = "Regular"
    ufo.info.unitsPerEm = upm
    ufo.info.ascender = font["hhea"].ascent
    ufo.info.descender = font["hhea"].descent
    ufo.info.capHeight = font["OS/2"].sCapHeight
    ufo.info.xHeight = font["OS/2"].sxHeight
    ufo.info.versionMajor = 1
    ufo.info.versionMinor = 0

    cmap = font.getBestCmap()
    rev = {}
    for cp, name in cmap.items():
        rev.setdefault(name, []).append(cp)

    order = font.getGlyphOrder()
    for name in order:
        if name == ".notdef":
            continue
        pen = DecomposingRecordingPen(glyphset)
        glyphset[name].draw(pen)
        g = ufo.newGlyph(name)
        g.width = font["hmtx"][name][0]
        g.unicodes = sorted(rev.get(name, []))
        seg_pen = SegmentToPointPen(g.getPointPen())
        qu = Qu2CuPen(seg_pen, max_err=0.3, all_cubic=True)
        pen.replay(qu)

    ufo.lib["public.glyphOrder"] = [n for n in order if n != ".notdef"]
    ufo.save(UFO, overwrite=True)
    print(f"saved {UFO}")

    gs = glyphsLib.to_glyphs([ufo])
    gs.save(GLYPHS)
    print(f"saved {GLYPHS}")


if __name__ == "__main__":
    sys.exit(main())
